/** Every flag that fires for a record, sorted with the most urgent first. */
export function checkRecord(record) {
  if (!record || !record.type) return [];
  const out = [];
  for (const r of RULES) {
    if (r.type !== record.type) continue;
    let fires = false;
    try { fires = !!r.when(record); } catch { fires = false; }
    if (!fires) continue;
    out.push({
      code: r.code, severity: r.severity, title: r.title,
      why: r.why(record), action: typeof r.action === "function" ? r.action(record) : r.action,
      source: r.src, say: r.say,
    });
  }
  return out.sort((a, b) => (a.severity === b.severity ? 0 : a.severity === "refer_now" ? -1 : 1));
}

export const flagCodes = (record) => checkRecord(record).map((f) => f.code).sort();
export const RULE_TABLE = RULES.map((r) => ({ code: r.code, type: r.type, severity: r.severity, title: r.title, action: typeof r.action === "function" ? r.action({}) : r.action, source: r.src }));
